-- reelscribe state + transcripts. Applied to the connection's current schema
-- (instagram_recap in production, a throwaway schema in tests).
CREATE TABLE reel (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url text NOT NULL UNIQUE, shortcode text NOT NULL UNIQUE,
  status text NOT NULL CHECK (status IN ('pending','running','done','failed')),
  added_at timestamptz NOT NULL, completed_at timestamptz, attempts int NOT NULL DEFAULT 0, last_error text,
  title text, uploader text, duration_s real, caption text, language text,
  audio_path text,            -- relative to REELSCRIBE_HOME
  transcript_file text,       -- markdown export basename (transition)
  ytdlp_meta jsonb);          -- full metadata, previously discarded
CREATE INDEX ON reel (status);
CREATE INDEX ON reel (added_at);
CREATE TABLE transcript (reel_id bigint PRIMARY KEY REFERENCES reel(id) ON DELETE CASCADE,
  text text NOT NULL, english_text text, note text, model text, transcribed_at timestamptz NOT NULL);
CREATE TABLE transcript_segment (reel_id bigint REFERENCES reel(id) ON DELETE CASCADE, idx int,
  start_s real NOT NULL, end_s real, text text NOT NULL, PRIMARY KEY (reel_id, idx));
